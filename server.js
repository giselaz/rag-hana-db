import express from 'express'
import { readFileSync } from 'node:fs'
import hana from '@sap/hana-client'
import { OrchestrationClient, OrchestrationEmbeddingClient } from '@sap-ai-sdk/orchestration'
const EMBED_MODEL = 'text-embedding-3-small'           // Gen AI Hub embedding model
const DIMS        = 1536                               // must match REAL_VECTOR(1536)
const CHAT_MODEL  = process.env.CHAT_MODEL || 'gpt-4o'
const TOP_K       = 3
const MIN_SCORE   = Number(process.env.MIN_SCORE || 0.3) // below this a chunk is "not relevant"
const TABLE       = 'RAG_CHUNKS'
// HANA connection 
const vcap  = JSON.parse(process.env.VCAP_SERVICES || readFileSync('./vcap.local.json', 'utf8'))
const creds = vcap.hana[0].credentials
const connParams = {
  serverNode: `${creds.host}:${creds.port}`,
  uid: creds.user,
  pwd: creds.password,
  currentSchema: creds.schema,
  encrypt: 'true',
  sslValidateCertificate: 'true'
}

// Run one SQL statement on a fresh connection
const q = (sql, params = []) => new Promise((resolve, reject) => {
  const conn = hana.createConnection()
  conn.connect(connParams, err => {
    if (err) return reject(err)
    conn.exec(sql, params, (err, rows) => {
      conn.disconnect()
      err ? reject(err) : resolve(rows)
    })
  })
})

// Gen AI Hub: embeddings + chat 
const embedder = new OrchestrationEmbeddingClient({
  embeddings: { model: { name: EMBED_MODEL } }
})

// type 'document' for stored chunks, 'query' for the search question
const embed = async (texts, type) => {
  let res
  try {
    res = await embedder.embed({ input: texts, type })
  } catch (e) {
    let c = e
    while (c.cause) c = c.cause                       // go to the innermost cause
    console.error('STATUS:', c.response?.status, 'DATA:', JSON.stringify(c.response?.data), 'MSG:', c.message)
    throw e
  }
  return res.getEmbeddings()
    .sort((a, b) => a.index - b.index)
    .map(e => JSON.stringify(e.embedding))
}

const chat = new OrchestrationClient({
  promptTemplating: {
    model: { name: CHAT_MODEL },
    prompt: {
      template: [
        {
          role: 'system',
          content: 'You are an IT Service Desk assistant. Answer ONLY from the context below. ' +
            'Cite sources as [1], [2] matching the context numbers. ' +
            'If the context does not contain the answer, reply exactly: "I don\'t know based on the knowledge base."\n\n' +
            'Context:\n{{?context}}'
        },
        { role: 'user', content: '{{?question}}' }
      ]
    }
  }
})

// ---------- Chunking: one chunk per paragraph, title kept with each chunk ----------
const chunkDoc = doc => doc.content
  .split(/\n\s*\n/)
  .map(p => p.trim())
  .filter(Boolean)
  .map(p => ({ title: doc.title, category: doc.category, text: `${doc.title}\n${p}` }))

// ---------- Retrieval: embed the query, rank chunks by cosine similarity ----------
const retrieve = async (query, top = TOP_K, category) => {
  const [qv] = await embed([query], 'query')
  const filter = category ? 'AND CATEGORY = ?' : ''         // metadata filter
  const rows = await q(
    `SELECT TOP ${Number(top) || TOP_K} ID, TITLE, CATEGORY, CHUNK,
            COSINE_SIMILARITY(EMBEDDING, TO_REAL_VECTOR(?)) AS SCORE
       FROM ${TABLE}
      WHERE EMBEDDING IS NOT NULL ${filter}
      ORDER BY SCORE DESC`,
    category ? [qv, category] : [qv])
  return rows.map(r => ({ id: r.ID, title: r.TITLE, category: r.CATEGORY, text: r.CHUNK, score: Number(Number(r.SCORE).toFixed(4)) }))
}

// ---------- Routes ----------
const app = express()
app.use(express.json())

// 1) Create the table (drops the old one)
app.post('/setup', async (_req, res) => {
  await q(`DROP TABLE ${TABLE}`).catch(() => {})            // ignore "table does not exist"
  await q(`CREATE TABLE ${TABLE} (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE     NVARCHAR(200),
    CATEGORY  NVARCHAR(50),
    CHUNK     NCLOB,
    EMBEDDING REAL_VECTOR(${DIMS})
  )`)
  res.json({ ok: true, table: TABLE })
})

// 2) Ingest: chunk docs.json, embed every chunk, store text + vector
app.post('/ingest', async (_req, res) => {
  const docs   = JSON.parse(readFileSync('./docs.json', 'utf8'))
  const chunks = docs.flatMap(chunkDoc)
  const vectors = await embed(chunks.map(c => c.text), 'document')
  for (let i = 0; i < chunks.length; i++) {
    await q(`INSERT INTO ${TABLE} (TITLE, CATEGORY, CHUNK, EMBEDDING) VALUES (?, ?, ?, TO_REAL_VECTOR(?))`,
      [chunks[i].title, chunks[i].category, chunks[i].text, vectors[i]])
  }
  res.json({ documents: docs.length, chunks: chunks.length })
})

// 3) Retrieve only: GET /search?q=...&top=3&category=network
app.get('/search', async (req, res) => {
  const { q: query, top, category } = req.query
  res.json({ query, results: await retrieve(query, top, category) })
})

// 4) RAG: retrieve, keep relevant chunks, ground the LLM answer in them
app.post('/ask', async (req, res) => {
  const { question, category } = req.body
  const hits = (await retrieve(question, TOP_K, category)).filter(h => h.score >= MIN_SCORE)
  const sources = hits.map(({ text, ...meta }) => meta)
  if (!hits.length) return res.json({ answer: "I don't know based on the knowledge base.", grounded: false, sources })

  const context = hits.map((h, i) => `[${i + 1}] ${h.text}`).join('\n\n')
  const out = await chat.chatCompletion({ placeholderValues: { context, question } })
  res.json({ answer: out.getContent(), grounded: true, sources })
})

app.listen(process.env.PORT || 4004, () => console.log(`hana-rag running on port ${process.env.PORT || 4004}`))